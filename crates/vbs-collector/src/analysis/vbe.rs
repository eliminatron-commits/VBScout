//! Decoder for scripts encoded with Microsoft's Script Encoder (`.vbe` files and
//! `VBScript.Encode` blocks). The encoding is a fixed, reversible substitution – not
//! encryption – so the collector can show the affected lines and find credentials in
//! encoded scripts as well.
//!
//! The substitution tables are those of Didier Stevens' `decode-vbe.py` (public domain),
//! which documents the format: `#@~^` + 6 characters length + `==`, the encoded text,
//! 6 characters checksum + `==^#~@`.

/// Decodes every encoded block in `text`; `None` if there is none.
pub fn decode_all(text: &str) -> Option<String> {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    let mut found = false;
    while let Some(start) = rest.find("#@~^") {
        let after = &rest[start + 4..];
        let Some(end) = after.find("^#~@") else { break };
        // 6 characters length + "==" before the data, 6 characters checksum + "==" after it.
        let Some(data) = after.get(8..end.saturating_sub(8)) else { break };
        out.push_str(&rest[..start]);
        out.push_str(&decode(data));
        rest = &after[end + 4..];
        found = true;
    }
    if !found {
        return None;
    }
    out.push_str(rest);
    Some(out)
}

/// Decodes the data part of one block.
fn decode(data: &str) -> String {
    let unescaped =
        data.replace("@&", "\n").replace("@#", "\r").replace("@*", ">").replace("@!", "<").replace("@$", "@");
    let mut out = String::with_capacity(unescaped.len());
    let mut index = 0usize;
    for c in unescaped.chars() {
        let code = c as u32;
        if code >= 128 {
            out.push(c);
            continue;
        }
        let byte = code as u8;
        let decodable = (byte == 9 || byte > 31) && !matches!(byte, b'<' | b'>' | b'@');
        if decodable {
            out.push(char::from(DECODE[usize::from(byte)][usize::from(PICK[index % 64])]));
        } else {
            out.push(c);
        }
        index += 1;
    }
    out
}

