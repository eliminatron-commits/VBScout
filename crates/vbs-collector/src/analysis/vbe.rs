#[cfg(test)]
mod tests {
    use super::*;

    /// The inverse substitution (what the Script Encoder does), to build test input.
    fn encode(plain: &str) -> String {
        let mut out = String::new();
        for (index, c) in plain.chars().enumerate() {
            let pick = usize::from(PICK[index % 64]);
            let byte = c as u8;
            let encoded = match c {
                '\n' => "@&".to_owned(),
                '\r' => "@#".to_owned(),
                '<' => "@!".to_owned(),
                '>' => "@*".to_owned(),
                '@' => "@$".to_owned(),
                _ => {
                    let source = (9u8..128)
                        .filter(|&e| (e == 9 || e > 31) && !matches!(e, b'<' | b'>' | b'@'))
                        .find(|&e| DECODE[usize::from(e)][pick] == byte)
                        .unwrap_or_else(|| panic!("{c:?} cannot be encoded"));
                    char::from(source).to_string()
                }
            };
            out.push_str(&encoded);
        }
        out
    }

    #[test]
    fn decodes_encoded_scripts() {
        let plain = "Set shell = CreateObject(\"WScript.Shell\")\r\nstrPwd = \"Sommer2024!\" ' <admin@example>\r\nshell.Run \"cmd /c dir\", 0";
        let file = format!("#@~^AAAAAA=={}AAAAAA==^#~@", encode(plain));
        assert!(!file.contains("CreateObject"));
        assert_eq!(decode_all(&file).as_deref(), Some(plain));
        let embedded =
            format!("<script language=\"VBScript.Encode\">#@~^AAAAAA=={}AAAAAA==^#~@</script>", encode("MsgBox 1"));
        assert_eq!(decode_all(&embedded).as_deref(), Some("<script language=\"VBScript.Encode\">MsgBox 1</script>"));
        assert_eq!(decode_all("MsgBox 1"), None);
    }

    #[test]
    fn every_printable_character_round_trips() {
        let plain: String = (32u8..127).map(char::from).chain(['\t']).collect();
        let file = format!("#@~^AAAAAA=={}AAAAAA==^#~@", encode(&plain));
        assert_eq!(decode_all(&file).as_deref(), Some(plain.as_str()));
    }
}
